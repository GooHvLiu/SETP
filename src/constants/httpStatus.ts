/**
 * ============================================================
 * 业务码 → HTTP 状态码映射（constants/httpStatus.ts）
 * ------------------------------------------------------------
 * 原则：
 *   1. HTTP 状态码表达传输层语义，业务码表达具体原因
 *   2. 成功统一 200；参数缺失 400；参数语义非法 422；
 *      未登录 401；无权限 403；不存在 404；冲突 409；
 *      限流 429；文件过大 413；媒体类型 415；
 *      上游失败 502；服务未配置 503；上游超时 504；系统错误 500
 *   3. 未登记的码一律 500，避免把未知错误伪装成 200
 * ============================================================
 */

